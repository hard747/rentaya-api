-- Tabla inicial de vehículos (herencia SINGLE_TABLE: AUTO, MOTO y CAMION en una sola tabla).
-- En la base de Neon esta tabla ya existía antes de Flyway: allí V1 queda como línea base.

CREATE TABLE vehiculos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                VARCHAR(31)    NOT NULL,
    placa               VARCHAR(7)     NOT NULL UNIQUE,
    marca               VARCHAR(100)   NOT NULL,
    modelo              VARCHAR(100)   NOT NULL,
    anio                INTEGER        NOT NULL,
    tarifa_diaria_base  NUMERIC(10, 2) NOT NULL,
    kilometraje         NUMERIC(12, 2) NOT NULL DEFAULT 0,
    activo              BOOLEAN        NOT NULL DEFAULT TRUE,
    numero_puertas      INTEGER,
    cilindrada          INTEGER,
    incluye_casco       BOOLEAN,
    capacidad_toneladas NUMERIC(8, 2),
    CONSTRAINT chk_tipo CHECK (tipo IN ('AUTO', 'MOTO', 'CAMION'))
);
