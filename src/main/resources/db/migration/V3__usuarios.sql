-- Etapa 5: cuentas de acceso. La contraseña se guarda como hash BCrypt, nunca en texto plano.
CREATE TABLE usuarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    rol           VARCHAR(20)  NOT NULL,
    cliente_id    BIGINT UNIQUE REFERENCES clientes (id),
    CONSTRAINT chk_rol CHECK (rol IN ('ADMIN', 'EMPLEADO', 'CLIENTE')),
    CONSTRAINT chk_cliente_rol CHECK ((rol = 'CLIENTE') = (cliente_id IS NOT NULL))
);
