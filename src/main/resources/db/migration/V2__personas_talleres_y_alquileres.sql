-- Etapa 3: personas (herencia JOINED), taller externo, calificaciones y alquileres.

-- Solo autos y motos se alquilan; para camiones la columna queda en TRUE y no se usa.
ALTER TABLE vehiculos ADD COLUMN disponible BOOLEAN NOT NULL DEFAULT TRUE;

-- Tabla padre de la jerarquía Persona: una fila por persona, sea del tipo que sea.
CREATE TABLE personas (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo   VARCHAR(31)  NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    dni    VARCHAR(8)   NOT NULL UNIQUE,
    CONSTRAINT chk_persona_tipo CHECK (tipo IN ('CLIENTE', 'CLIENTE_PREMIUM', 'CONDUCTOR', 'MECANICO'))
);

-- Cada subtipo guarda solo sus columnas propias y comparte el id con su tabla padre.
CREATE TABLE clientes (
    id    BIGINT PRIMARY KEY REFERENCES personas (id),
    email VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE clientes_premium (
    id                   BIGINT PRIMARY KEY REFERENCES clientes (id),
    porcentaje_descuento NUMERIC(5, 2) NOT NULL,
    CONSTRAINT chk_descuento CHECK (porcentaje_descuento BETWEEN 0 AND 30)
);

CREATE TABLE empleados (
    id               BIGINT PRIMARY KEY REFERENCES personas (id),
    sueldo_base      NUMERIC(10, 2) NOT NULL,
    anios_antiguedad INTEGER        NOT NULL,
    CONSTRAINT chk_sueldo CHECK (sueldo_base > 0),
    CONSTRAINT chk_antiguedad CHECK (anios_antiguedad >= 0)
);

CREATE TABLE conductores (
    id         BIGINT PRIMARY KEY REFERENCES empleados (id),
    licencia   CHAR(1) NOT NULL,
    viajes_mes INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT chk_licencia CHECK (licencia IN ('A', 'B', 'C'))
);

CREATE TABLE mecanicos (
    id              BIGINT PRIMARY KEY REFERENCES empleados (id),
    especialidad    VARCHAR(100) NOT NULL,
    horas_extra_mes INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE conductor_calificaciones (
    conductor_id BIGINT  NOT NULL REFERENCES conductores (id),
    estrellas    INTEGER NOT NULL,
    CONSTRAINT chk_estrellas_conductor CHECK (estrellas BETWEEN 1 AND 5)
);

CREATE TABLE talleres_externos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social        VARCHAR(150)   NOT NULL,
    ruc                 VARCHAR(11)    NOT NULL UNIQUE,
    monto_facturado_mes NUMERIC(12, 2) NOT NULL DEFAULT 0
);

CREATE TABLE taller_calificaciones (
    taller_id BIGINT  NOT NULL REFERENCES talleres_externos (id),
    estrellas INTEGER NOT NULL,
    CONSTRAINT chk_estrellas_taller CHECK (estrellas BETWEEN 1 AND 5)
);

-- Un alquiler une un cliente con un vehículo (relaciones muchos a uno).
CREATE TABLE alquileres (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id       BIGINT         NOT NULL REFERENCES clientes (id),
    vehiculo_id      BIGINT         NOT NULL REFERENCES vehiculos (id),
    dias             INTEGER        NOT NULL,
    costo_total      NUMERIC(12, 2) NOT NULL,
    estado           VARCHAR(20)    NOT NULL,
    fecha_inicio     TIMESTAMP      NOT NULL,
    fecha_devolucion TIMESTAMP,
    km_recorridos    NUMERIC(12, 2),
    CONSTRAINT chk_dias CHECK (dias > 0),
    CONSTRAINT chk_estado_alquiler CHECK (estado IN ('ACTIVO', 'FINALIZADO'))
);

CREATE INDEX idx_alquileres_cliente ON alquileres (cliente_id);
CREATE INDEX idx_alquileres_vehiculo ON alquileres (vehiculo_id);
