-- Etapa 6: historial de pagos mensuales a empleados y al taller externo.
CREATE TABLE pagos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periodo       VARCHAR(7)     NOT NULL,
    tipo          VARCHAR(20)    NOT NULL,
    beneficiario  VARCHAR(150)   NOT NULL,
    identificador VARCHAR(11)    NOT NULL,
    monto         NUMERIC(12, 2) NOT NULL,
    fecha_pago    TIMESTAMP      NOT NULL,
    CONSTRAINT uq_pago_periodo UNIQUE (periodo, identificador),
    CONSTRAINT chk_monto CHECK (monto >= 0)
);

CREATE INDEX idx_pagos_periodo ON pagos (periodo);
